def test_config_files_keeps_only_regular_files():
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as tar:
        for name, data in (("firewalld/zones/external.xml", b"<zone/>"),
                           ("firewalld/firewalld.conf", b"DefaultZone=external\n")):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
        d = tarfile.TarInfo("firewalld/zones")
        d.type = tarfile.DIRTYPE
        tar.addfile(d)
        link = tarfile.TarInfo("firewalld/evil")
        link.type = tarfile.SYMTYPE
        link.linkname = "/etc/shadow"
        tar.addfile(link)

    s = _bare_session()
    s.exec = lambda command, sink, timeout, limit_bytes=None: sink.write(raw.getvalue())
    files = s.config_files()
    assert files == {
        "firewalld/zones/external.xml": b"<zone/>",
        "firewalld/firewalld.conf": b"DefaultZone=external\n",
    }


