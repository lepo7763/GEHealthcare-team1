def _bare_session():
    s = FirewallSession.__new__(FirewallSession)
    s.config = FirewallConfig()
    s._error = FirewallCollectionError
    return s


def test_run_commands_enters_host_namespaces(monkeypatch):
    monkeypatch.setattr(collector_mod.secrets, "token_hex", lambda n: "abc")
    s = _bare_session()
    seen = {}

    def fake_exec_text(command, timeout_seconds=60):
        seen["command"] = command
        return "@@FW-abc@@ BEGIN default_zone\nexternal\n\n@@FW-abc@@ END default_zone 0\n"

    s.exec_text = fake_exec_text
    assert s.run_commands() == {"default_zone": ("external\n", 0)}
    cmd = seen["command"]
    assert cmd[:7] == ["nsenter", "-t", "1", "-m", "-n", "-p", "--"]
    assert cmd[-1] == "@@FW-abc@@"


