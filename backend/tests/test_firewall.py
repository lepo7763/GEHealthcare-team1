class FakeSession:
    def __init__(self, outputs=None, files=None, fail_enter=None, fail_files=None):
        self.outputs = outputs or _outputs()
        self.files = files if files is not None else {"firewalld/zones/external.xml": b"<zone/>"}
        self.fail_enter = fail_enter
        self.fail_files = fail_files
        self.pod_name = "firewall-collector-x-abc"
        self.node_name = "n1"

    def __call__(self, core, batch, config):
        return self

    def __enter__(self):
        if self.fail_enter:
            raise self.fail_enter
        return self

    def __exit__(self, *exc):
        pass

    def run_commands(self, commands=None):
        return self.outputs

    def config_files(self):
        if self.fail_files:
            raise self.fail_files
        return self.files


