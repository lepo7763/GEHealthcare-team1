def test_parse_zones():
    zones = {z.name: z for z in parse_zones(ZONES)}
    assert list(zones) == ["block", "docker", "external"]
    assert zones["docker"].active and zones["docker"].interfaces == ["docker0"]
    ext = zones["external"]
    assert ext.services == ["ntp", "ssh"] and "6443/tcp" in ext.ports
    assert ext.masquerade is True and ext.forward is False and ext.icmp_block_inversion
    assert ext.rich_rules == [
        'rule family="ipv4" icmp-type name="timestamp-request" drop',
        'rule family="ipv4" icmp-type name="timestamp-reply" drop',
    ]
    assert zones["block"].target == "%%REJECT%%" and zones["block"].rich_rules == []


def test_parse_header_flags():
    z = parse_zones("public (default, active)\n  target: default\n")[0]
    assert z.is_default and z.active


def test_parse_policies_keeps_extra_fields():
    p = parse_zones(POLICIES)[0]
    assert p.other == {"priority": "-15000", "ingress-zones": "ANY", "egress-zones": "HOST"}
    assert p.rich_rules == ['rule family="ipv6" icmp-type name="redirect" accept']


def test_zone_drift():
    runtime = parse_zones(ZONES.replace("ports: 2380/tcp", "ports: 8080/tcp 2380/tcp"))
    drift = zone_drift(runtime, parse_zones(ZONES))
    assert [(d.zone, d.field) for d in drift] == [("external", "ports")]
    assert "8080/tcp" in drift[0].runtime and "8080/tcp" not in drift[0].permanent
    assert zone_drift(parse_zones(ZONES), parse_zones(ZONES)) == []


def test_parse_iptables_save():
    tables = {t.name: t for t in parse_iptables_save(IPTABLES)}
    assert (tables["nat"].chains, tables["nat"].rules) == (3, 1)
    assert tables["filter"].policies == {"INPUT": "ACCEPT", "FORWARD": "DROP", "OUTPUT": "ACCEPT"}
    assert tables["filter"].rules == 2


def test_unassigned_interfaces():
    names = parse_interfaces(LINKS)
    assert names == ["lo", "eno1", "docker0", "veth1a2b3c"]
    assert unassigned_interfaces(names, parse_zones(ZONES)) == ["eno1"]


