# --- framing: run the generated script for real --------------------------------


def _stub(dir_, name, body):
    path = os.path.join(dir_, name)
    with open(path, "w") as f:
        f.write("#!/bin/sh\n" + body)
    os.chmod(path, 0o755)


def test_script_frames_every_command_with_exit_codes(tmp_path):
    bin_dir = str(tmp_path)
    _stub(bin_dir, "firewall-cmd", 'case "$1" in\n'
          "  --query-lockdown) echo no; exit 1;;\n"
          "  --state) echo 'not running' >&2; exit 252;;\n"
          '  *) echo "fw $*";;\nesac\n')
    _stub(bin_dir, "iptables-save", "printf '*filter\\nCOMMIT\\n'\n")  # ends in newline
    _stub(bin_dir, "systemctl", "printf active\n")  # no trailing newline
    token = "@@FW-test@@"
    script = build_script()
    env = {"PATH": f"{bin_dir}:/usr/bin:/bin"}
    out = subprocess.run(
        ["sh", "-c", script, "sh", token], capture_output=True, text=True, env=env,
        check=True,
    ).stdout
    results = parse_framed(out, token)
    assert set(results) == {c.id for c in COMMANDS}
    assert results["lockdown"] == ("no\n", 1)  # exact output, newline kept
    assert results["firewalld_state"] == ("not running\n", 252)  # stderr captured
    assert results["iptables_save"] == ("*filter\nCOMMIT\n", 0)
    assert results["firewalld_service_active"] == ("active", 0)
    assert results["zones_runtime"] == ("fw --list-all-zones\n", 0)
    assert results["nft_ruleset"][1] == 127  # not installed in the stub PATH


def test_parse_framed_ignores_noise_and_unclosed_frames():
    t = "@@T@@"
    out = f"junk\n{t} BEGIN a\nline1\n{t} END b 0\nline2\n\n{t} END a 3\n{t} BEGIN c\nhalf"
    assert parse_framed(out, t) == {"a": (f"line1\n{t} END b 0\nline2\n", 3)}


def test_commands_are_fixed_and_read_only():
    words = " ".join(" ".join(c.argv) for c in COMMANDS)
    for forbidden in ("--add", "--remove", "--set", "--reload", "-F", "-D", "-I", "flush"):
        assert f" {forbidden}" not in f" {words}"
    assert len({c.id for c in COMMANDS}) == len(COMMANDS)


