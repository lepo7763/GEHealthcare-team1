def test_snapshot_from_outputs():
    snap = build_snapshot(_outputs(), "2026-11-14T00:00:00Z", node="n1")
    fw = snap.firewalld
    assert (fw.installed, fw.state, fw.version, fw.default_zone) == (True, "running", "0.9.3", "external")
    assert fw.lockdown is False and fw.panic_mode is False  # exit 1 = "no", not an error
    assert next(z for z in snap.zones if z.name == "external").is_default
    assert snap.unassigned_interfaces == ["eno1"]
    assert snap.iptables_backend == "legacy" and snap.ipv6_enabled is False
    assert snap.errors == [] and {c.status for c in snap.commands} == {"ok"}


def test_snapshot_flags_failures_and_missing_tools():
    snap = build_snapshot(
        _outputs(
            nft_ruleset=("", 127),
            iptables_save=("iptables-save: permission denied", 1),
        ),
        "t",
    )
    status = {c.id: c.status for c in snap.commands}
    assert status["nft_ruleset"] == "missing" and status["iptables_save"] == "error"
    assert snap.iptables_v4 == []
    assert snap.errors == ["iptables-save failed (exit 1): iptables-save: permission denied"]


